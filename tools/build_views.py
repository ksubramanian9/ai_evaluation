"""Generate derived views from node frontmatter.

Usage (from repo root):  python tools/build_views.py [--stale-days 90]

Writes:
  map/00-overview.md   Mermaid diagrams + branch tables
  progress.md          status table and counts
  study-plan.md        week-by-week plan (see --hours-per-week)
Also validates prerequisites and reports landscape entries older than N days.
No third-party dependencies.
"""
import argparse
import datetime as dt
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP = ROOT / "map"
STATUSES = ["not-started", "learning", "practiced", "mastered"]
DEPTHS = ["L1", "L2", "L3"]
BRIDGES = ["stats", "testing", "none"]
TAGS = ["nondeterminism", "statistics", "human-labels", "llm-judge", "rag", "agents",
        "safety", "security", "fairness", "privacy", "cost"]
REQUIRED_HEADINGS = ["## Learning objectives", "## Why it matters", "## Common failure modes", "## Practice exercise",
                     "## Mastery check", "## Sources"]


def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            v = [x.strip() for x in v[1:-1].split(",") if x.strip()]
        else:
            v = v.strip('"')
        meta[k.strip()] = v
    meta["path"] = path.relative_to(ROOT).as_posix()
    return meta


def load():
    nodes = {}
    for p in sorted(MAP.rglob("*.md")):
        if p.name.startswith("_") or p.name == "00-overview.md":
            continue
        n = parse(p)
        nodes[n["id"]] = n
    return nodes


def validate(nodes):
    errs = []
    for n in nodes.values():
        if n["status"] not in STATUSES:
            errs.append(f"{n['id']}: bad status {n['status']}")
        stem = pathlib.PurePosixPath(n["path"]).stem
        if n["id"] != stem:
            errs.append(f"{n['id']}: id does not match filename stem {stem}")
        if n.get("depth") not in DEPTHS:
            errs.append(f"{n['id']}: bad depth {n.get('depth')!r} (expected one of {DEPTHS})")
        if n.get("bridge") not in BRIDGES:
            errs.append(f"{n['id']}: bad bridge {n.get('bridge')!r} (expected one of {BRIDGES})")
        tags = n.get("tags", [])
        if not isinstance(tags, list):
            tags = [tags]
        bad = [t for t in tags if t not in TAGS]
        if bad:
            errs.append(f"{n['id']}: tags not in controlled vocabulary: {', '.join(bad)}")
        body = (ROOT / n["path"]).read_text(encoding="utf-8")
        heads = [l.strip() for l in body.splitlines() if l.startswith("## ")]
        for req in REQUIRED_HEADINGS:
            if not any(h == req or h.startswith(req + " ") or (req.endswith("exercise") and h.startswith(req)) for h in heads):
                errs.append(f"{n['id']}: missing required heading '{req}'")
        for q in n["prerequisites"]:
            if q not in nodes:
                errs.append(f"{n['id']}: unknown prerequisite {q}")
    # cycle check
    state = {}

    def visit(i, stack):
        if state.get(i) == 2:
            return
        if state.get(i) == 1:
            errs.append("cycle: " + " -> ".join(stack + [i]))
            return
        state[i] = 1
        for q in nodes[i]["prerequisites"]:
            if q in nodes:
                visit(q, stack + [i])
        state[i] = 2

    for i in nodes:
        visit(i, [])
    return errs


def branches(nodes):
    out = {}
    for n in nodes.values():
        out.setdefault(n["branch"], []).append(n)
    return dict(sorted(out.items()))


def mm(i):
    return "n_" + i.replace("-", "_")


def overview(nodes):
    br = branches(nodes)
    L = ["# Map overview", "", "_Generated by `tools/build_views.py`. Do not edit by hand._", ""]
    L += ["## Branch-level view", "", "```mermaid", "flowchart LR"]
    for b, ns in br.items():
        L.append(f'  {mm(b)}["{b}<br/>{len(ns)} nodes"]')
    seen = set()
    for n in nodes.values():
        for q in n["prerequisites"]:
            a, c = nodes[q]["branch"], n["branch"]
            if a != c and (a, c) not in seen:
                seen.add((a, c))
                L.append(f"  {mm(a)} --> {mm(c)}")
    L += ["```", ""]
    for b, ns in br.items():
        L += [f"## {b}", "", "```mermaid", "flowchart TD"]
        for n in ns:
            L.append(f'  {mm(n["id"])}["{n["title"]}"]')
        for n in ns:
            for q in n["prerequisites"]:
                if nodes[q]["branch"] == b:
                    L.append(f"  {mm(q)} --> {mm(n['id'])}")
        L += ["```", "", "| Node | Depth | Bridge | Cross-branch prerequisites |", "|---|---|---|---|"]
        for n in ns:
            ext = ", ".join(q for q in n["prerequisites"] if nodes[q]["branch"] != b) or "-"
            rel = pathlib.PurePosixPath(n["path"]).relative_to("map").as_posix()
            L.append(f"| [{n['title']}]({rel}) | {n['depth']} | {n['bridge']} | {ext} |")
        L.append("")
    return "\n".join(L)


def progress(nodes):
    br = branches(nodes)
    L = ["# Progress", "", "_Generated by `tools/build_views.py`. Change a node's `status` in its frontmatter, then re-run._", ""]
    L += ["| Branch | " + " | ".join(STATUSES) + " | total |", "|---|" + "---|" * (len(STATUSES) + 1)]
    for b, ns in br.items():
        c = [sum(1 for n in ns if n["status"] == s) for s in STATUSES]
        L.append(f"| {b} | " + " | ".join(map(str, c)) + f" | {len(ns)} |")
    L += ["", "## Nodes", "", "| Node | Branch | Depth | Bridge | Status |", "|---|---|---|---|---|"]
    for n in nodes.values():
        L.append(f"| [{n['title']}]({n['path']}) | {n['branch']} | {n['depth']} | {n['bridge']} | {n['status']} |")
    return "\n".join(L) + "\n"


def layers(nodes):
    """Learning-path stage: longest prerequisite chain depth (0 = no prerequisites)."""
    memo = {}

    def depth(i):
        if i not in memo:
            ps = nodes[i]["prerequisites"]
            memo[i] = 0 if not ps else 1 + max(depth(p) for p in ps)
        return memo[i]

    for i in nodes:
        depth(i)
    return memo


READING_HOURS = {"L1": 1, "L2": 2, "L3": 3}
DEFAULT_EXERCISE_HOURS = 3


def exercise_hours(node):
    """Upper bound of the hours in '## Practice exercise (N h)' or '(A-B h)'."""
    text = (ROOT / node["path"]).read_text(encoding="utf-8")
    m = re.search(r"(?m)^## Practice exercise\s*\(([\d.]+)(?:\s*[-–]\s*([\d.]+))?\s*h\)", text)
    if not m:
        return DEFAULT_EXERCISE_HOURS
    return float(m.group(2) or m.group(1))


def fmt_h(x):
    return str(int(x)) if float(x) == int(x) else f"{x:g}"


def study_plan(nodes, hours_per_week=6.0):
    """Return dict(weeks=[[item,...],...], total, hpw, skipped, steps). Items carry node, hours."""
    lay = layers(nodes)
    order = sorted(nodes.values(), key=lambda n: (lay[n["id"]], n["branch"], n["title"]))
    placed = set(n["id"] for n in order if n["status"] == "mastered")
    pending = [n for n in order if n["status"] != "mastered"]
    seq = []
    while pending:  # stable topological pass: first pending node whose prerequisites are all placed
        for n in pending:
            if all(q in placed for q in n["prerequisites"]):
                seq.append(n)
                placed.add(n["id"])
                pending.remove(n)
                break
        else:  # cycle (validate() reports these); avoid looping forever
            seq.extend(pending)
            break
    weeks, cur, used = [], [], 0.0
    for n in seq:
        h = exercise_hours(n) + READING_HOURS.get(n["depth"], 2)
        if cur and used + h > hours_per_week:
            weeks.append(cur)
            cur, used = [], 0.0
        cur.append({"node": n, "hours": h})
        used += h
    if cur:
        weeks.append(cur)
    # capstone steps become doable once all their nodes are covered (planned or mastered)
    week_of = {it["node"]["id"]: wi for wi, w in enumerate(weeks, 1) for it in w}
    steps = []
    cap = ROOT / "capstone" / "README.md"
    if cap.exists():
        for line in cap.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\|\s*(\d+)\s*\|\s*\*\*(.+?)\*\*", line)
            if not m:
                continue
            ids = [i for i in re.findall(r"map/[^)\s]*?/([\w-]+)\.md", line) if i in nodes]
            if ids:
                wk = max(week_of.get(i, 0) for i in ids)
                steps.append({"n": int(m.group(1)), "title": m.group(2).rstrip("."), "week": wk})
    total = sum(it["hours"] for w in weeks for it in w)
    return {"weeks": weeks, "total": total, "hpw": hours_per_week,
            "skipped": sum(1 for n in nodes.values() if n["status"] == "mastered"), "steps": steps}


def study_plan_md(nodes, hours_per_week=6.0):
    sp = study_plan(nodes, hours_per_week)
    weeks = sp["weeks"]
    L = ["# Study plan", "", "_Generated by `tools/build_views.py`. Do not edit by hand._", ""]
    L += [f"**{fmt_h(sp['total'])} hours over {len(weeks)} weeks** at {fmt_h(hours_per_week)} h/week "
          f"({sum(len(w) for w in weeks)} nodes; {sp['skipped']} mastered nodes skipped).", "",
          "How it is built:", "",
          "- Order: learning-path stage (longest prerequisite chain), then branch, then title. A node is never scheduled before its prerequisites.",
          "- Hours per node = practice exercise hours (upper bound of the range in the node's heading) + reading allowance by depth (L1 1 h, L2 2 h, L3 3 h).",
          "- Weeks are filled in order up to the budget. A node never splits across weeks; a node larger than the budget gets its own week.",
          "- Change the budget with `python tools/build_views.py --hours-per-week N`.", ""]
    for wi, w in enumerate(weeks, 1):
        L += [f"## Week {wi} ({fmt_h(sum(i['hours'] for i in w))} h)", "",
              "| Node | Branch | Depth | Hours | Status |", "|---|---|---|---|---|"]
        for it in w:
            n = it["node"]
            L.append(f"| [{n['title']}]({n['path']}) | {n['branch']} | {n['depth']} | {fmt_h(it['hours'])} | {n['status']} |")
        done = [s for s in sp["steps"] if s["week"] == wi]
        if done:
            L += ["", "Capstone steps doable after this week: " + "; ".join(f"step {s['n']} ({s['title']})" for s in done)]
        L.append("")
    early = [s for s in sp["steps"] if s["week"] == 0]
    if early:
        L += ["## Capstone steps already doable", "", "; ".join(f"step {s['n']} ({s['title']})" for s in early), ""]
    return "\n".join(L)


def stale(days):
    """Landscape entries must contain 'as-of: YYYY-MM-DD'."""
    out = []
    today = dt.date.today()
    for p in sorted((ROOT / "landscape").glob("*.md")):
        for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            m = re.search(r"as-of:\s*(\d{4}-\d{2}-\d{2})", line)
            if m:
                age = (today - dt.date.fromisoformat(m.group(1))).days
                if age > days:
                    out.append(f"{p.name}:{i} is {age} days old")
    return out


def landscape_warnings():
    """Non-fatal: entries should carry '(type: ...)' and a URL or 'URL not recorded'."""
    out = []
    for p in sorted((ROOT / "landscape").glob("*.md")):
        for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            if not line.startswith("- ") or "(none yet)" in line or line.startswith("- <item>"):
                continue
            if "(type:" not in line:
                out.append(f"{p.name}:{i} missing '(type: ...)'")
            if not re.search(r"https?://", line) and "URL not recorded" not in line:
                out.append(f"{p.name}:{i} missing URL or 'URL not recorded'")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stale-days", type=int, default=90)
    ap.add_argument("--hours-per-week", type=float, default=6.0)
    a = ap.parse_args()
    nodes = load()
    errs = validate(nodes)
    if errs:
        print("\n".join(errs))
        sys.exit(1)
    (MAP / "00-overview.md").write_text(overview(nodes), encoding="utf-8")
    (ROOT / "progress.md").write_text(progress(nodes), encoding="utf-8")
    (ROOT / "study-plan.md").write_text(study_plan_md(nodes, a.hours_per_week), encoding="utf-8")
    sp = study_plan(nodes, a.hours_per_week)
    print(f"{len(nodes)} nodes OK; wrote map/00-overview.md, progress.md and study-plan.md "
          f"({fmt_h(sp['total'])} h, {len(sp['weeks'])} weeks at {fmt_h(a.hours_per_week)} h/week)")
    for s in stale(a.stale_days):
        print("STALE:", s)
    for w in landscape_warnings():
        print("WARN:", w)


if __name__ == "__main__":
    main()
